const FONT = { glyphs: {}, atlas: null, colored: new Map(), cell: 8, lineH: 10 };
(function buildFont() {
  const keys = Object.keys(GLYPH_SRC);
  const [atlas, g] = makeCanvas(keys.length * FONT.cell, 10);
  g.fillStyle = '#fff';
  keys.forEach((ch, i) => {
    const rows = GLYPH_SRC[ch].split('/');
    let w = 0;
    rows.forEach(r => { w = Math.max(w, r.length); });
    rows.forEach((r, y) => {
      for (let x = 0; x < r.length; x++) if (r[x] === '#') g.fillRect(i * FONT.cell + x, y, 1, 1);
    });
    FONT.glyphs[ch] = { i, w };
  });
  FONT.atlas = atlas;
})();
const CHAR_MAP = { '’': "'", '‘': "'", '“': '"', '”': '"', '—': '-', '–': '-', '…': '...', 'É': 'E', 'è': 'e', 'á': 'a', 'ñ': 'n', 'ü': 'u', 'ö': 'o' };
function normText(s) {
  let o = '';
  for (const ch of String(s)) o += CHAR_MAP[ch] !== undefined ? CHAR_MAP[ch] : ch;
  return o;
}
function fontAtlas(col) {
  let a = FONT.colored.get(col);
  if (a) return a;
  const [c, g] = makeCanvas(FONT.atlas.width, FONT.atlas.height);
  g.drawImage(FONT.atlas, 0, 0);
  g.globalCompositeOperation = 'source-in';
  g.fillStyle = col;
  g.fillRect(0, 0, c.width, c.height);
  FONT.colored.set(col, c);
  return c;
}
function glyphOf(ch) { return FONT.glyphs[ch] || FONT.glyphs['?']; }
function textWidth(s, scale) {
  s = normText(s); scale = scale || 1;
  let w = 0;
  for (const ch of s) w += glyphOf(ch).w + 1;
  return Math.max(0, w - 1) * scale;
}
// opts: {scale, align:'left'|'center'|'right', shadow:col, outline:col, alpha}
function drawText(s, x, y, col, opts) {
  opts = opts || {};
  s = normText(s);
  const scale = opts.scale || 1;
  const w = textWidth(s, scale);
  if (opts.align === 'center') x -= w / 2;
  else if (opts.align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  const g = opts.g || ctx;
  const prevA = g.globalAlpha;
  if (opts.alpha !== undefined) g.globalAlpha = prevA * opts.alpha;
  if (opts.outline) {
    const o = scale;
    for (const [dx, dy] of [[-o, 0], [o, 0], [0, -o], [0, o], [-o, -o], [o, -o], [-o, o], [o, o]]) blitText(g, s, x + dx, y + dy, opts.outline, scale);
  }
  if (opts.shadow) blitText(g, s, x + scale, y + scale, opts.shadow, scale);
  blitText(g, s, x, y, col || '#fff', scale);
  g.globalAlpha = prevA;
  return w;
}
function blitText(g, s, x, y, col, scale) {
  const atlas = fontAtlas(col);
  let cx = x;
  for (const ch of s) {
    const gl = glyphOf(ch);
    g.drawImage(atlas, gl.i * FONT.cell, 0, gl.w, 10, cx, y, gl.w * scale, 10 * scale);
    cx += (gl.w + 1) * scale;
  }
}
function wrapText(s, maxW, scale) {
  s = normText(s);
  const out = [];
  for (const para of s.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const wd of words) {
      const test = line ? line + ' ' + wd : wd;
      if (textWidth(test, scale) <= maxW || !line) line = test;
      else { out.push(line); line = wd; }
    }
    out.push(line);
  }
  return out;
}
// shorten a string with "..." so it fits maxW pixels
function fitText(s, maxW, scale) {
  if (textWidth(s, scale) <= maxW) return s;
  let t = s;
  while (t.length > 1 && textWidth(t + '...', scale) > maxW) t = t.slice(0, -1);
  return t.trimEnd() + '...';
}
